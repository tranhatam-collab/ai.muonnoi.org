import { readdir,readFile,mkdtemp,copyFile,writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { createHash } from 'node:crypto';
import assert from 'node:assert/strict';
import { localStore } from './local-store.mjs';
import { Coordinator } from '../src/coordinator.ts';
const started=Date.now(),dir=new URL('../.local/backups/',import.meta.url);
const manifests=(await readdir(dir)).filter(n=>n.endsWith('.sqlite.json')).sort();assert.ok(manifests.length,'Create local backup first');
const manifest=JSON.parse(await readFile(new URL(manifests.at(-1),dir),'utf8'));
assert.match(manifest.file,/^revenueops-[\dTZ.\-]+\.sqlite$/);
const source=new URL(manifest.file,dir),bytes=await readFile(source);
assert.equal(createHash('sha256').update(bytes).digest('hex'),manifest.sha256,'Checksum mismatch');
const restoreDir=await mkdtemp(join(tmpdir(),'revenueops-restore-'));const target=join(restoreDir,'isolated.sqlite');await copyFile(source,target);
const store=localStore(target);assert.equal(store.rows('PRAGMA integrity_check')[0].integrity_check,'ok');
const coordinator=new Coordinator(store);const actor={id:'restore-drill',role:'owner'};
const before=coordinator.report(actor);const count=store.rows('SELECT COUNT(*) AS n FROM jobs')[0].n;
coordinator.planDay(actor);coordinator.planDay(actor);const after=store.rows('SELECT COUNT(*) AS n FROM jobs')[0].n;
assert.ok(after===count || after===count+10);assert.equal(coordinator.report(actor).actuals.netVnd,null);
const receipt={scope:'LOCAL_SQLITE_ONLY',backup:manifest.file,sha256:manifest.sha256,restoredTo:target,integrity:'ok',jobsBefore:count,jobsAfter:after,reservationCount:before.reservations.length,durationMs:Date.now()-started,checkedAt:new Date().toISOString(),productionRestore:'NOT_CHECKED'};
store.close();await writeFile(new URL('../docs/evidence/local-restore.json',import.meta.url),JSON.stringify(receipt,null,2)+'\n');console.log(JSON.stringify(receipt,null,2));
